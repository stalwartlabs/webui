import { useTranslation } from 'react-i18next';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { FormSectionCard } from '@/components/forms/FormSections';
import { htmlToText, previewDocument, vacationPreview } from '../model';
import type { FieldValues } from '@/components/forms/formLogic';

function TextBody({ text, note }: { text: string; note?: string }) {
  return (
    <div className="space-y-2">
      {note && <p className="text-xs text-muted-foreground">{note}</p>}
      <p className="whitespace-pre-wrap break-words text-sm leading-relaxed">{text}</p>
    </div>
  );
}

export function VacationPreview({ data }: { data: FieldValues }) {
  const { t } = useTranslation();
  const preview = vacationPreview(data);
  const derivedNote = t(
    'vacation.textFromHtml',
    'Generated by the server from the HTML body; line breaks may differ slightly.',
  );

  return (
    <FormSectionCard title={t('vacation.preview', 'Preview')}>
      <div className="space-y-4 py-4">
        <div className="space-y-1">
          <span className="eyebrow block">{t('vacation.subject', 'Subject')}</span>
          {preview.subject ? (
            <p className="break-words text-sm font-semibold">{preview.subject}</p>
          ) : (
            <p className="text-sm text-muted-foreground">
              {t('vacation.defaultSubject', 'Chosen by the server, usually "Auto:" followed by the original subject.')}
            </p>
          )}
        </div>
        <div className="space-y-1.5">
          <span className="eyebrow block">{t('vacation.message', 'Message')}</span>
          {preview.html === null ? (
            <TextBody
              text={preview.text ?? ''}
              note={
                data.textBody ? undefined : t('vacation.defaultText', 'No message set: the server sends this text.')
              }
            />
          ) : (
            <Tabs defaultValue="html">
              <TabsList>
                <TabsTrigger value="html">{t('vacation.htmlTab', 'HTML')}</TabsTrigger>
                <TabsTrigger value="text">{t('vacation.textTab', 'Plain text')}</TabsTrigger>
              </TabsList>
              <TabsContent value="html" className="pt-2">
                <iframe
                  title={t('vacation.htmlPreview', 'HTML reply preview')}
                  sandbox=""
                  srcDoc={previewDocument(preview.html)}
                  className="h-64 w-full rounded-xl border-0 bg-white"
                />
              </TabsContent>
              <TabsContent value="text" className="pt-2">
                {preview.textFromHtml ? (
                  <TextBody text={htmlToText(preview.html)} note={derivedNote} />
                ) : (
                  <TextBody text={preview.text ?? ''} />
                )}
              </TabsContent>
            </Tabs>
          )}
        </div>
        <p className="text-xs text-muted-foreground">
          {t('vacation.spamNote', 'Replies are never sent to messages classified as spam.')}
        </p>
      </div>
    </FormSectionCard>
  );
}
